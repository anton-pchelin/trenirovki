// Упражнения «на время» внутри «свой вес» — поле время вместо повторов
const TIME_ONLY = /\(время\)/;
const DIST_ONLY = /\(м\)/;

export const CATEGORIES = Object.keys(RAW);

export const EXERCISES = [];
for (const [cat, [type, names]] of Object.entries(RAW)) {
  names.forEach((name, i) => {
    const ex = { id: `${cat.slice(0, 3)}${i}`, name: name.replace(/ \((время|м)\)/, ''), cat, type };
    if (TIME_ONLY.test(name)) ex.fields = ['t'];
    if (DIST_ONLY.test(name)) ex.fields = ['d'];
    if (name === 'Подтягивания с отягощением') ex.fields = ['w', 'r'];
    if (cat === 'Кардио' && name === 'Скакалка (время)') ex.fields = ['t'];
    EXERCISES.push(ex);
  });
}
